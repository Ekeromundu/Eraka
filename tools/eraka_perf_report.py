#!/usr/bin/env python3
"""
Eraka technical performance: turns what the phone logged into the thesis numbers.

    python tools/eraka_perf_report.py perf.txt [startup.txt] [meminfo*.txt] [--apk app-release.apk]

Inputs (any mix, any number of files):
  - logcat:   adb logcat -s ErakaPerf whisper ActivityTaskManager > perf.txt
  - startup:  output of  adb shell am start -W -S -n na.eraka.app/na.eraka.welcome.SplashActivity
              (one block per cold start; "TotalTime: 812")
  - memory:   output of  adb shell dumpsys meminfo na.eraka.app   ("TOTAL PSS: 84,123" or "TOTAL  84123")
Writes perf_report.md and perf_table.tex next to the first input file.
"""
import argparse
import os
import re
import statistics
import sys

MEASURES = [  # key, label in the thesis, unit
    ("cold_start", "Cold start to first screen (Android)", "ms"),
    ("start_to_board", "Start of the app to board ready", "ms"),
    ("board_displayed", "Board displayed (Android)", "ms"),
    ("model_build", "Building the prediction model from the log", "ms"),
    ("predict_probs", "Model: scoring all pictures (tiles)", "ms"),
    ("predict_rank", "Model: ranking for the tiles", "ms"),
    ("predict_row", "Model: ranking for the suggestion row", "ms"),
    ("smart_row", "Refreshing the suggestion row", "ms"),
    ("tap_to_board", "Tap to updated board (main thread)", "ms"),
    ("whisper_load", "Loading the Whisper model", "ms"),
    ("whisper_transcribe", "Speech recognition per word", "ms"),
    ("memory_pss", "Memory used (PSS)", "MB"),
]
PERF = re.compile(r"ErakaPerf\s*:\s*(\w+) ms=([\d.]+)(.*)")
WHISPER = re.compile(r"Transcribe finished in (\d+)ms")
DISPLAYED = re.compile(r"Displayed \S+?/(\S+?)(?: for user \d+)?: \+(?:(\d+)s)?(\d+)ms")
TOTALTIME = re.compile(r"^\s*TotalTime:\s*(\d+)", re.M)
PSS = re.compile(r"TOTAL PSS:\s*([\d,]+)|^\s*TOTAL\s+([\d,]+)\s", re.M)
TAPS = re.compile(r"taps=(\d+)")


def read(paths):
    vals = {k: [] for k, _, _ in MEASURES}
    model_taps = []
    for p in paths:
        raw = open(p, "rb").read()
        # PowerShell's ">" writes UTF-16; cmd and Linux write UTF-8
        enc = "utf-16" if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else "utf-8-sig"
        text = raw.decode(enc, errors="replace")
        for line in text.splitlines():
            m = PERF.search(line)
            if m and m.group(1) in vals:
                vals[m.group(1)].append(float(m.group(2)))
                t = TAPS.search(m.group(3))
                if m.group(1) == "model_build" and t:
                    model_taps.append(int(t.group(1)))
            m = WHISPER.search(line)
            if m:
                vals["whisper_transcribe"].append(float(m.group(1)))
            m = DISPLAYED.search(line)
            if m and m.group(1).endswith("MainBoardActivity"):
                vals["board_displayed"].append(int(m.group(2) or 0) * 1000 + int(m.group(3)))
        vals["cold_start"] += [float(x) for x in TOTALTIME.findall(text)]
        # one value per dumpsys output: "TOTAL PSS:" (newer Android) or the "TOTAL" row (older)
        for block in re.split(r"(?=\*\* MEMINFO)", text):
            hits = PSS.findall(block)
            pss = [a for a, b in hits if a] or [b for a, b in hits if b]
            if pss:
                vals["memory_pss"].append(int(pss[0].replace(",", "")) / 1024)
    return vals, model_taps


def fmt(x, unit):
    if unit == "MB":
        return f"{x:.0f}"
    return f"{x:.0f}" if x >= 10 else f"{x:.1f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+")
    ap.add_argument("--apk", help="the APK you installed, to report its size")
    a = ap.parse_args()
    vals, model_taps = read(a.files)

    md = ["# Eraka technical performance", "",
          "| measure | n | median | min | max | unit |", "|---|---|---|---|---|---|"]
    tex = ["% Rows for the technical performance table. Generated by tools/eraka_perf_report.py",
           r"% Measure & n & Median & Range \\"]
    for key, label, unit in MEASURES:
        v = vals[key]
        if not v:
            md.append(f"| {label} | 0 | - | - | - | {unit} |")
            continue
        med, lo, hi = statistics.median(v), min(v), max(v)
        md.append(f"| {label} | {len(v)} | {fmt(med, unit)} | {fmt(lo, unit)} | {fmt(hi, unit)} | {unit} |")
        tex.append(f"{label} & {len(v)} & {fmt(med, unit)}~{unit} & {fmt(lo, unit)}--{fmt(hi, unit)}~{unit} \\\\")
    if model_taps:
        md.append(f"\nPrediction model built from {min(model_taps)}-{max(model_taps)} logged taps.")
    if a.apk and os.path.exists(a.apk):
        mb = os.path.getsize(a.apk) / 1024 / 1024
        md.append(f"\nAPK size: {mb:.1f} MB ({os.path.basename(a.apk)}).")
        tex.append(f"Size of the installed file (APK) & 1 & {mb:.0f}~MB & -- \\\\")
    missing = [label for key, label, _ in MEASURES if not vals[key]]
    if missing:
        md.append("\nNot measured yet: " + "; ".join(missing) + ".")
    out_dir = os.path.dirname(os.path.abspath(a.files[0]))
    open(os.path.join(out_dir, "perf_report.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    open(os.path.join(out_dir, "perf_table.tex"), "w", encoding="utf-8").write("\n".join(tex) + "\n")
    print("\n".join(md))
    print(f"-> {out_dir}/perf_report.md and perf_table.tex")


if __name__ == "__main__":
    sys.exit(main())
